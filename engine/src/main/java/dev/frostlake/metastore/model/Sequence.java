package dev.frostlake.metastore.model;

import dev.frostlake.executor.StatementClock;

import java.time.Instant;
import java.util.concurrent.atomic.AtomicLong;

/**
 * Represents a database SEQUENCE object
 */
public class Sequence {
    private String name;
    /** The value the next draw serves: the START value until something is drawn, whatever the step becomes. */
    private final AtomicLong nextValue;
    private final long startValue;
    private long increment;
    private boolean order;
    private String comment;
    // The creating statement's instant, which a replayed statement reproduces (see SqlObject).
    private Instant createdTime = StatementClock.instant();
    /** When the last DDL after the CREATE ran, or null while the CREATE is the last; see {@link #getLastDdlTime}. */
    private Instant lastDdlTime;
    /** Whether anything was drawn, and the value drawn last. */
    private volatile boolean drawn;
    private volatile long lastValue;
    /** The schema that holds the sequence, or null once it is dropped from one. */
    private volatile Schema home;

    public Sequence(final String name, final long startValue, final long increment, final boolean order, final String comment) {
        this.name = name;
        this.startValue = startValue;
        this.increment = increment;
        this.order = order;
        this.nextValue = new AtomicLong(startValue);
        this.comment = comment;
    }

    /**
     * Get the next value in the sequence (NEXTVAL). A draw also computes the value after it, and a step that would
     * leave the 64-bit range fails the draw, and every draw after it, with {@code Sequence value has exceeded valid
     * range in sequence object S.} — so the last value inside the range is never handed out (live-verified).
     */
    public long nextVal() {
        while (true) {
            final long value = nextValue.get();
            final long after;
            try {
                after = Math.addExact(value, increment);
            } catch (final ArithmeticException outOfRange) {
                throw new RuntimeException("Sequence value has exceeded valid range in sequence object " + name + ".");
            }
            if (nextValue.compareAndSet(value, after)) {
                lastValue = value;
                drawn = true;
                return value;
            }
        }
    }

    /**
     * Get the current value of the sequence (CURRVAL)
     * Returns the last value generated by NEXTVAL
     */
    public long currVal() {
        // If no NEXTVAL has been called yet, throw exception
        if (!drawn) {
            throw new RuntimeException("CURRVAL cannot be called before NEXTVAL for sequence: " + name);
        }
        return lastValue;
    }

    /**
     * The value one step before the next one — what a clone and a snapshot carry, to be handed back to
     * {@link #setCurrentValue(long)} under the same step. This does not check if NEXTVAL was called.
     */
    public long getCurrentValueRaw() {
        return nextValue.get() - increment;
    }

    /**
     * The value the NEXT call to {@link #nextVal()} will return, without consuming it — the
     * catalog's NEXT_VALUE. On a sequence nothing has drawn from yet this is its START value.
     */
    public long peekNextValue() {
        return nextValue.get();
    }

    /**
     * Restores the value one step before the next one, as {@link #getCurrentValueRaw()} gave it.
     */
    public void setCurrentValue(final long value) {
        nextValue.set(value + increment);
        drawn = value != startValue - increment;
        lastValue = value;
    }

    /** Owning role; defaults to SYSADMIN until stamped with the creating role at CREATE. */
    private String owner = "SYSADMIN";

    public String getName() {
        return name;
    }

    /** The sequence's new canonical name (ALTER SEQUENCE … RENAME TO), its value and settings kept. */
    public void setName(final String name) {
        this.name = name;
    }

    public String getOwner() {
        return owner;
    }

    public void setOwner(final String owner) {
        this.owner = owner;
    }

    public long getStartValue() {
        return startValue;
    }

    public long getIncrement() {
        return increment;
    }

    /**
     * Change the step applied by future NEXTVAL calls (ALTER SEQUENCE … SET INCREMENT). The value already computed
     * with the old step is still handed out next, and the new step applies from the value after it: the documented
     * example's sequence at 1, 2, 3 goes on 4, then 0 under INCREMENT -4. A sequence nothing has drawn from serves its
     * START value first. The account may skip further ahead, as it caches values, and a sequence makes no promise
     * against gaps.
     */
    public void setIncrement(final long increment) {
        this.increment = increment;
    }

    /** When this sequence was created, as SHOW SEQUENCES reports it. */
    public Instant getCreatedTime() {
        return createdTime;
    }

    /**
     * Put back when this object was created, as a snapshot recorded it, so an engine clone or a restore reports the
     * original creation time. A null, from a snapshot that never recorded it, keeps the time it was rebuilt.
     *
     * @param created the recorded creation time, or null
     */
    public void restoreCreatedTime(final Instant created) {
        if (created != null) {
            this.createdTime = created;
        }
    }

    /**
     * When the last DDL statement ran on this sequence, which is INFORMATION_SCHEMA.SEQUENCES' LAST_ALTERED: its CREATE
     * until an ALTER or a COMMENT ON moves it. Drawing a value is not DDL, and nothing documents NEXTVAL moving it.
     *
     * @return the instant
     */
    public Instant getLastDdlTime() {
        return lastDdlTime != null ? lastDdlTime : createdTime;
    }

    /** A DDL statement changed this sequence: its LAST_ALTERED moves to the statement's instant. */
    public void markDdl() {
        lastDdlTime = StatementClock.instant();
    }

    /**
     * Put back when the last DDL ran on this sequence, as a snapshot recorded it; a null, from a snapshot that never
     * recorded it, leaves LAST_ALTERED at the creation.
     *
     * @param lastDdl the recorded last DDL, or null
     */
    public void restoreLastDdlTime(final Instant lastDdl) {
        if (lastDdl != null) {
            this.lastDdlTime = lastDdl;
        }
    }

    public boolean isOrder() {
        return order;
    }

    /**
     * The schema that holds the sequence — what names it in full wherever a column bound to it is described.
     *
     * @return the schema, or null once the sequence is dropped
     */
    public Schema getHome() {
        return home;
    }

    /** Records the schema the sequence is added to, or null when it is dropped from one. */
    void setHome(final Schema home) {
        this.home = home;
    }

    /** Whether the sequence serves its values in order (ALTER SEQUENCE … SET NOORDER). */
    public void setOrder(final boolean order) {
        this.order = order;
    }

    public String getComment() {
        return comment;
    }

    public void setComment(final String comment) {
        this.comment = comment;
    }

    public String getObjectType() {
        return "SEQUENCE";
    }

    @Override
    public String toString() {
        return "Sequence{" +
                "name='" + name + '\'' +
                ", nextValue=" + nextValue.get() +
                ", startValue=" + startValue +
                ", increment=" + increment +
                '}';
    }
}
