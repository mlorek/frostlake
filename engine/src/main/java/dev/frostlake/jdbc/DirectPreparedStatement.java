package dev.frostlake.jdbc;

import dev.frostlake.DatabaseEngine;

import java.sql.BatchUpdateException;
import java.sql.Connection;
import java.sql.ParameterMetaData;
import java.sql.ResultSet;
import java.sql.ResultSetMetaData;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * The in-process transport's prepared statement: its execution and batches over the embedded engine, with the
 * parameter setters of {@link FrostlakePreparedStatement}.
 */
public class DirectPreparedStatement extends DirectStatement implements FrostlakePreparedStatement {

    private final String sql;
    private final Map<Integer, Object> parameters = new HashMap<>();
    private final List<Map<Integer, Object>> batchParameters = new ArrayList<>();
    private final Map<Integer, String> batchBindTypes = new HashMap<>();
    private final int autoGeneratedKeys;

    public DirectPreparedStatement(final Connection connection, final DatabaseEngine engine, final String sql) {
        this(connection, engine, sql, Statement.NO_GENERATED_KEYS);
    }

    public DirectPreparedStatement(final Connection connection, final DatabaseEngine engine, final String sql, final int autoGeneratedKeys) {
        super(connection, engine);
        this.sql = sql;
        this.autoGeneratedKeys = autoGeneratedKeys;
    }

    @Override
    public Map<Integer, Object> boundParameters() {
        return parameters;
    }

    @Override
    public ResultSet executeQuery() throws SQLException {
        return executeQuery(buildSql());
    }

    @Override
    public int executeUpdate() throws SQLException {
        return executeUpdate(buildSql(), autoGeneratedKeys);
    }

    @Override
    public boolean execute() throws SQLException {
        return execute(buildSql(), autoGeneratedKeys);
    }

    protected String buildSql() throws SQLException {
        // Inlined client-side (no server-side binding); escapes literals and skips '?' inside string literals.
        // (Replaces a replaceFirst loop that also mis-interpreted $ / \ in the replacement value.)
        return JdbcMarshaling.bindPrepared(sql, parameters);
    }

    /**
     * Result-column metadata for a result-returning statement (null for DML / non-queries). Describes the query
     * by executing a copy with every unbound placeholder set to NULL — for a parameterized SELECT this returns
     * zero rows (so it is cheap) while still carrying the projection's columns.
     */
    private ResultSetMetaData prepareResultMetaData() throws SQLException {
        final String head = sql.trim().toUpperCase(Locale.ROOT);
        if (!(head.startsWith("SELECT") || head.startsWith("WITH") || head.startsWith("SHOW")
                || head.startsWith("DESC") || head.startsWith("EXPLAIN") || head.startsWith("CALL"))) {
            return null;
        }
        final Map<Integer, Object> filled = new HashMap<>(parameters);
        final int count = JdbcMarshaling.countPlaceholders(sql);
        for (int i = 1; i <= count; i++) {
            filled.putIfAbsent(i, null);
        }
        return executeQuery(JdbcMarshaling.substitutePlaceholders(sql, filled)).getMetaData();
    }

    @Override
    public void addBatch() throws SQLException {
        checkClosed();
        // Live refuses a row whose bind types differ from the earlier rows' (array binding).
        JdbcBindTypes.validateBatchRow(batchBindTypes, parameters, batchParameters.size() + 1);
        // Save a copy of current parameters
        final Map<Integer, Object> paramsCopy = new HashMap<>(parameters);
        batchParameters.add(paramsCopy);
    }

    @Override
    public void clearBatch() throws SQLException {
        checkClosed();
        batchParameters.clear();
        batchBindTypes.clear();
    }

    /**
     * Live executes a prepared batch as one array-bound statement: a failure surfaces as that
     * statement's own {@link SQLException} — never a {@link BatchUpdateException} — and the batch
     * applies nothing. Frostlake executes the rows one by one, so rows before the failing one
     * stay applied; the exception surface matches live, and the remaining rows are not attempted.
     */
    @Override
    public int[] executeBatch() throws SQLException {
        checkClosed();
        final int[] results = new int[batchParameters.size()];
        int index = 0;
        long total = 0;

        try {
            for (final Map<Integer, Object> params : batchParameters) {
                // Temporarily set parameters for this batch entry
                final Map<Integer, Object> savedParams = new HashMap<>(parameters);
                parameters.clear();
                parameters.putAll(params);
                try {
                    // Live Snowflake reports the real affected-row count per batch entry, not
                    // SUCCESS_NO_INFO.
                    results[index] = executeUpdate();
                    total += results[index];
                } finally {
                    // Restore original parameters
                    parameters.clear();
                    parameters.putAll(savedParams);
                }
                index++;
            }
        } finally {
            // Clear batch after execution
            batchParameters.clear();
            batchBindTypes.clear();
        }
        // The driver runs the batch as ONE array-bound statement, so what getUpdateCount() reports after it is
        // the whole batch's count (live-verified: two one-row entries leave 2).
        takeBatchCount(total);
        return results;
    }

    @Override
    public ResultSetMetaData getMetaData() throws SQLException {
        return prepareResultMetaData();
    }

    @Override
    public ParameterMetaData getParameterMetaData() throws SQLException {
        return new JdbcParameterMetaData(JdbcMarshaling.countPlaceholders(sql));
    }

}
