    @Test
    public void aPendingRunCarriesItsGraphRunsIds() {
        engine.execute(
            "CREATE OR REPLACE TABLE t (a INT)");
        engine.execute(
            "CREATE OR REPLACE TASK tk_sch_w7 SCHEDULE = '60 MINUTE' AS SELECT 1");
        engine.execute(
            "ALTER TASK tk_sch_w7 RESUME");
        engine.execute(
            "SHOW TASKS LIKE 'TK_SCH_W7'");
        try {
            assertAnswer(
                "true",
                "SELECT (SELECT \"id\" FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))) = (SELECT "
                    + "ANY_VALUE(root_task_id) FROM TABLE(INFORMATION_SCHEMA.TASK_HISTORY(TASK_NAME => 'tk_sch_w7')))");
            assertAnswer(
                "true",
                "SELECT run_id = DATE_PART(epoch_millisecond, scheduled_time) FROM "
                    + "TABLE(INFORMATION_SCHEMA.TASK_HISTORY(TASK_NAME => 'tk_sch_w7'))");
        } finally {
            engine.execute(
                "ALTER TASK IF EXISTS tk_sch_w7 SUSPEND");
            engine.execute(
                "DROP TASK IF EXISTS tk_sch_w7");
        }
    }
