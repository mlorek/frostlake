    @Test
    public void anAlertListsTheTaskParametersWithoutTheTasksOwn() {
        engine.execute("CREATE OR REPLACE ALERT al_p SCHEDULE = '60 MINUTE' IF (EXISTS (SELECT 1)) THEN SELECT 1");
        engine.execute("SHOW PARAMETERS IN ALERT al_p");
        assertAnswer("145", "SELECT COUNT(*) FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))");
        engine.execute("SHOW PARAMETERS IN ALERT al_p");
        assertAnswer(KEYS, "SELECT LISTAGG(\"key\", ',') WITHIN GROUP (ORDER BY \"key\") FROM "
            + "TABLE(RESULT_SCAN(LAST_QUERY_ID()))");
        assertCells(new String[][] {
            {"SHOW PARAMETERS IN ALERT nosuch_al",
                "REFUSED SQL compilation error: | Alert 'TEST_DB.TEST_SCHEMA.NOSUCH_AL' does not exist or not "
                + "authorized. Your primary role <ROLE> must have at least one privilege granted on ALERT "
                + "TEST_DB.TEST_SCHEMA.NOSUCH_AL."},
            {"SHOW PARAMETERS IN ALERT", "REFUSED SQL compilation error: | This session does not have a current alert"},
            {"SHOW PARAMETERS IN ALERT test_db.test_schema.al_p LIMIT 1",
                "REFUSED SQL compilation error: | syntax error line 1 at position 50 unexpected 'LIMIT'."},
        });
    }
